// Regenerates types/api.ts from the backend's OpenAPI document.
//
//   pnpm api:types                    # from the running backend (OPENAPI_URL, default below)
//   pnpm api:types ../openapi.json    # from a file (CI: backend `app.scripts.export_openapi`)
//
// A Node script rather than the openapi-typescript CLI so it works the same in PowerShell,
// Git Bash and CI (no shell-specific env-default syntax, no .cmd shim; see frontend.md).
//
// Keys are sorted first: the live /openapi.json lists paths and schemas in route order, the
// exported file in sorted order, and openapi-typescript keeps whatever order it gets. Sorting
// here makes both sources produce the same file, so CI's drift check never flags a reorder.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import openapiTS, { astToString } from "openapi-typescript";

const DEFAULT_URL = "http://localhost:8000/openapi.json";
const OUTPUT = resolve(import.meta.dirname, "../types/api.ts");

const arg = process.argv[2];
const source = arg || process.env.OPENAPI_URL || DEFAULT_URL;

async function load(location) {
  if (/^https?:\/\//.test(location)) {
    const response = await fetch(location);
    if (!response.ok) throw new Error(`GET ${location} failed: ${response.status}`);
    return response.json();
  }
  return JSON.parse(readFileSync(resolve(process.cwd(), location), "utf8"));
}

/** Objects get their keys sorted (recursively); array order is meaningful and kept. */
function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value === null || typeof value !== "object") return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, sortKeys(value[key])]),
  );
}

const header =
  "// Generated by `pnpm api:types` from the backend OpenAPI document. Do not edit by hand.\n\n";

const ast = await openapiTS(sortKeys(await load(source)));
writeFileSync(OUTPUT, header + astToString(ast));
console.log(`types/api.ts written from ${source}`);
